import textwrap

CREATE_PAYMENT = textwrap.dedent(
    """
    ## 🔐 API name:
    ### Create new payment

    ***********************

    ## 📝 API Description:
    - Принимает запрос на оплату и ставит его в асинхронную обработку.
    - Пишет платёж и событие `payments.new` в БД в одной транзакции (Outbox pattern) —
      публикация в очередь гарантируется отдельным фоновым релеем, даже если в момент
      запроса RabbitMQ недоступен.
    - Не дожидается результата обработки — сразу возвращает `202 Accepted` со статусом `pending`.
    - Идемпотентна: повторный запрос с тем же `Idempotency-Key` не создаёт новый платёж,
      а возвращает уже существующий (тот же `payment_id`, тот же текущий статус).

    ***********************

    ## 📥 Expected values:
    - Заголовок (обязателен):
        - **Idempotency-Key** – уникальный ключ идемпотентности для защиты от дублей.
    - Request body (JSON):
        - **amount** – сумма платежа (decimal, > 0).
        - **currency** – валюта: `RUB`, `USD` или `EUR`.
        - **description** (опционально) – описание платежа.
        - **metadata** (опционально) – произвольные метаданные платежа (JSON-объект).
        - **webhook_url** – URL, на который будет отправлено уведомление о результате обработки.

    ***********************

    ## 🛡️ Validation of accepted values:
    - **Idempotency-Key** обязателен — без него запрос будет отклонён с `422`.
    - **amount** должен быть строго больше нуля.
    - **currency** должна быть одной из `RUB` / `USD` / `EUR`.
    - **webhook_url** должен быть корректным URL.
    - Повторный запрос с уже использованным **Idempotency-Key** не считается ошибкой —
      возвращается ранее созданный платёж.

    ***********************

    ## 📤 Returned data:
    - Возвращает краткую информацию о поставленном в обработку платеже.

    ### Response fields description:

    ### Payment-related fields:
    - **payment_id** – уникальный идентификатор платежа.
    - **status** – текущий статус платежа (`pending` сразу после создания).
    - **created_at** – дата и время создания платежа.

    ### Example response:

    ```json
    {
        "payment_id": "27ea6b8f-17fa-4a7b-a9f6-31b8dc76abe4",
        "status": "pending",
        "created_at": "2026-09-17T11:38:44.037751Z"
    }
    ```

    ***********************

    ## ⚠️ Exceptions:
    - **401 Unauthorized** – если заголовок `X-API-Key` отсутствует или неверен.
    - **422 Unprocessable Entity** – если тело запроса или заголовок `Idempotency-Key` не прошли валидацию.
    - **400 Bad Request** – если платёж не удалось создать по внутренней причине.

    ***********************

    ## 💬 Comments:
    - Дальнейшая обработка платежа (эмуляция шлюза, ретраи, webhook) происходит асинхронно
      через отдельный consumer — статус платежа стоит проверять через `GET /api/v1/payments/{payment_id}`.
    - После создания платёж всегда находится в статусе `pending`, даже если запрос был
      идемпотентным повтором — конечный статус (`succeeded`/`failed`) зависит от текущего
      состояния уже существующего платежа.
    ***********************
    """
)


GET_PAYMENT = textwrap.dedent(
    """
    ## 🔐 API name:
    ### Get payment by id

    ***********************

    ## 📝 API Description:
    - Возвращает полную информацию о платеже по его идентификатору.
    - Используется для отслеживания статуса асинхронно обрабатываемого платежа.

    ***********************

    ## 📥 Expected values:
    - Path-параметр:
        - **payment_id** – идентификатор платежа, полученный при создании.

    ***********************

    ## 🛡️ Validation of accepted values:
    - Если платёж с указанным `payment_id` не найден, запрос завершится ошибкой `404`.

    ***********************

    ## 📤 Returned data:
    - Возвращает полную информацию о платеже.

    ### Response fields description:

    ### Payment-related fields:
    - **payment_id** – уникальный идентификатор платежа.
    - **amount** – сумма платежа.
    - **currency** – валюта платежа (`RUB` / `USD` / `EUR`).
    - **description** – описание платежа (может быть `null`).
    - **metadata** – метаданные платежа (может быть `null`).
    - **status** – текущий статус: `pending`, `succeeded` или `failed`.
    - **webhook_url** – URL, на который отправляется уведомление о результате.
    - **created_at** – дата и время создания платежа.
    - **processed_at** – дата и время завершения обработки (`null`, пока платёж `pending`).

    ### Example response:

    ```json
    {
        "payment_id": "27ea6b8f-17fa-4a7b-a9f6-31b8dc76abe4",
        "amount": 199.99,
        "currency": "RUB",
        "description": "Order #42",
        "metadata": {"order_id": 42},
        "status": "succeeded",
        "webhook_url": "https://example.com/webhook",
        "created_at": "2026-09-17T11:38:44.037751Z",
        "processed_at": "2026-09-17T11:38:47.512340Z"
    }
    ```

    ***********************

    ## ⚠️ Exceptions:
    - **401 Unauthorized** – если заголовок `X-API-Key` отсутствует или неверен.
    - **404 Not Found** – если платёж с указанным `payment_id` не найден.

    ***********************

    ## 💬 Comments:
    - Статус меняется асинхронно с `pending` на `succeeded`/`failed` — обычно в течение
      нескольких секунд, дольше при повторных попытках обработки (retry).
    - `processed_at` заполняется только после того, как обработка платежа завершится
      (успешно или окончательно неуспешно).
    ***********************
    """
)
